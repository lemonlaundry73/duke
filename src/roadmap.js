// The Duke Forger roadmap: 9 phases, 67 steps, from idea to released open-world game.
// Each step says what to do in plain words, which role you are playing, how AI helps,
// what you fill in (inputs), which workspace panels it opens, and the gate that must pass
// before the next step unlocks.
//
// Gate checks:
//   {t:'input', key}          an answer the creator wrote (validated by its field rules)
//   {t:'auto', id, label}     verified by Duke from the project, the build agent or the PC
//   {t:'proof', key, label, min}  screenshots or files the creator uploads as evidence
//   {t:'self', label}         a self-check the creator ticks (things no software can verify)

const T=(key,label,o={})=>({key,label,type:'text',...o});
const A=(key,label,o={})=>({key,label,type:'textarea',...o});
const S=(key,label,options,o={})=>({key,label,type:'select',options,...o});
const NUM=(key,label,o={})=>({key,label,type:'number',...o});
const L=(key,label,o={})=>({key,label,type:'list',...o});
const inp=key=>({t:'input',key});
const auto=(id,label)=>({t:'auto',id,label});
const proof=(key,label,min=1)=>({t:'proof',key,label,min});
const self=label=>({t:'self',label});

