const TEMPLATE=path.join(path.dirname(fileURLToPath(import.meta.url)),'template');
const VEHICLE_LEN={Motorbike:2.2,Truck:7,SUV:4.9,Police:4.8,Sports:4.5,Muscle:4.9,Sedan:4.7};
const WEAPON_LEN={Pistol:.25,SMG:.5,'Assault rifle':.9,Shotgun:1,'Sniper rifle':1.2,Melee:.9};

async function walk(dir,base=dir){
  const out=[];
  for(const e of await fs.readdir(dir,{withFileTypes:true})){
    const p=path.join(dir,e.name);
    if(e.isDirectory())out.push(...await walk(p,base));else out.push(path.relative(base,p).split(path.sep).join('/'));
  }
  return out;
}
const localFile=pub=>pub&&pub.startsWith('/uploads/')?path.join(UPLOAD_DIR,pub.replace(/^\/uploads\//,'')):null;
const exists=async f=>!!f&&!!(await fs.stat(f).catch(()=>null));
const safeName=s=>String(s||'Duke Game').replace(/[^A-Za-z0-9 _-]/g,'').trim()||'Duke Game';
const ini=s=>String(s||'').replace(/[\r\n"]/g,' ').slice(0,120);

// Parse a screenplay-style opening script into subtitle lines.
export function parseScript(text){
  const out=[];let speaker='';
  for(const raw of String(text||'').split(/\r?\n/)){
    const line=raw.trim();
    if(!line){speaker='';continue;}
    if(/^(INT\.|EXT\.|INT\/EXT|CUT TO|FADE (IN|OUT)|SMASH CUT)/i.test(line))continue;
    if(/^\(.*\)$/.test(line))continue; // parenthetical
    const cue=line.replace(/\s*\(.*\)\s*$/,'');
    if(cue.length<40&&cue===cue.toUpperCase()&&/[A-Z]/.test(cue)&&!/[.!?]$/.test(cue)){speaker=cue.replace(/\s*\(\d+\)$/,'');continue;}
    out.push({speaker:speaker?speaker.split(' ').map(w=>w[0]+w.slice(1).toLowerCase()).join(' '):'',text:line});
  }
  return out.slice(0,60);
}

export function gameData(p){
  const d=ensureDesign(p),v=d.vision||{},w=d.world||{},sys=d.systems||{},cb=d.combat||{},au=d.audio_ui||{};
  return {
    title:v.title||p.name,menuTitle:au.menu_title||v.title||p.name,cityName:w.city_name||v.title||p.name,music:au.music_style||'',
    startTime:Number(w.default_time??17.5),weather:w.weather||'Mostly clear',traffic:w.traffic||'Normal',crowds:w.crowds||'Normal',
    wanted:sys.wanted_enabled!==false,maxWanted:Number(sys.max_wanted)||5,startCash:Number(sys.start_cash)||0,
    playerHealth:Number(cb.player_health)||100,aimStyle:cb.aim_style||'Free aim',armor:cb.armor!==false,
    hud:{minimap:au.hud_minimap!==false,wanted:au.hud_wanted!==false,cash:au.hud_cash!==false,subtitles:au.subtitles!==false},
    radio:au.radio_stations||[],intro:parseScript(d.story?.opening_script),
    characters:(d.characters||[]).map(c=>({id:c.id,name:c.name,role:c.role,personality:c.personality||'',height:Number(c.height_m)||1.78,meshYaw:-90,
      lines:String(c.dialogue||'').split(/\n/).map(x=>x.trim().replace(/^["“]|["”]$/g,'')).filter(Boolean)})),
    vehicles:(d.vehicles||[]).map(x=>({id:x.id,name:x.name,class:x.class,spawn:x.spawn||'Traffic',handling:x.handling||'Balanced',topSpeed:Number(x.top_speed_kmh)||180,
      length:VEHICLE_LEN[x.class]||4.6,yaw:x.art?.yaw||0})),
    weapons:(d.weapons||[]).map(x=>({id:x.id,name:x.name,type:x.type,damage:Number(x.damage)||25,rpm:Number(x.fire_rate_rpm)||400,range:Number(x.range_m)||50,
      magazine:Number(x.magazine)||15,price:Number(x.price)||0,yaw:x.art?.yaw||0,length:WEAPON_LEN[x.type]||.5})),
    missions:(d.missions||[]).map(m=>({id:m.id,name:m.name,giver:m.giver,objective:m.objective,district:m.district,target:m.target||'',reward:Number(m.reward)||0,briefing:m.briefing||''}))
  };
}

export function layoutFor(p){
  const d=ensureDesign(p);
  const city=buildCity((p.world?.seed||7)>>>0,{n:SIZES[d.world?.size]||12,districts:(d.districts||[]).filter(x=>x.name&&x.style),landmarks:(d.landmarks||[]).filter(x=>x.district)});
  const L=exportLayout(city);
  for(const lm of L.landmarks){const src=(d.landmarks||[]).find(x=>x.id===lm.id);lm.yaw=src?.art?.yaw||0;}
  return L;
}

export async function buildUnrealProject(p){
  const d=ensureDesign(p);
  const title=safeName(d.vision?.title||p.name);
  const root=title.replace(/\s+/g,'');
  const files=[];
  const add=(name,data,store=false)=>files.push({name:`${root}/${name}`,data,store});
  for(const rel of await walk(TEMPLATE))add(rel,await fs.readFile(path.join(TEMPLATE,rel)));
  const engine=String(d.build?.engine_version||'').match(/^5\.\d+$/)?d.build.engine_version:'';
  add('DukeGame.uproject',JSON.stringify({FileVersion:3,EngineAssociation:engine,Category:'',Description:`${title} — generated by Duke Forge`,
    Modules:[{Name:'DukeGame',Type:'Runtime',LoadingPhase:'Default',AdditionalDependencies:['Engine','CoreUObject']}],
    Plugins:[{Name:'PythonScriptPlugin',Enabled:true},{Name:'EditorScriptingUtilities',Enabled:true},{Name:'EnhancedInput',Enabled:true},{Name:'Interchange',Enabled:true},{Name:'GLTFImporter',Enabled:true}]},null,2));
  add('Config/DefaultGame.ini',`; Generated by Duke Forge
[/Script/EngineSettings.GeneralProjectSettings]
ProjectName=${ini(title)}
CompanyName=${ini(d.publish?.itch_user||'Independent creator')}
Description=${ini(d.vision?.logline)}
ProjectVersion=1.0.0

[/Script/UnrealEd.ProjectPackagingSettings]
BuildConfiguration=PPBC_${d.build?.config==='Development'?'Development':'Shipping'}
bUseIoStore=True
bShareMaterialShaderCode=True
bSharedMaterialNativeLibraries=True
IncludePrerequisites=True
+DirectoriesToAlwaysCook=(Path="/Game/Duke")
+DirectoriesToAlwaysStageAsUFS=(Path="Duke/Data")
+MapsToCook=(FilePath="/Engine/Maps/Entry")
`);
  add('Content/Duke/Data/game.json',JSON.stringify(gameData(p),null,2));
  add('Content/Duke/Data/layout.json',JSON.stringify(layoutFor(p)));
  // creator assets
  const manifest={characters:{},vehicles:{},weapons:{},landmarks:{},kit:{}};
  const missing=[];
  const take=async(pub,dest)=>{const f=localFile(pub);if(!(await exists(f)))return null;add(dest,await fs.readFile(f),true);return dest;};
  for(const c of d.characters||[]){
    const a=c.art||{};if(!a.rig?.fbx){missing.push(`${c.name||'character'}: no rigged model`);continue;}
    const base=`Import/characters/${c.id}`;const entry={rig:await take(a.rig.fbx,`${base}/rig.fbx`),anims:{}};
    for(const [k,v] of Object.entries(a.anims||{}))if(v?.fbx){const got=await take(v.fbx,`${base}/anim_${k}.fbx`);if(got)entry.anims[k]=got;}
    if(entry.rig)manifest.characters[c.id]=entry;else missing.push(`${c.name}: rig file missing on server`);
  }
  for(const [group,list] of [['vehicles',d.vehicles],['weapons',d.weapons],['landmarks',d.landmarks]])for(const e of list||[]){
    const m=e.art?.model;if(!m){missing.push(`${e.name||group}: no 3D model`);continue;}
    const base=`Import/${group}/${e.id}`;const entry={glb:m.glb?await take(m.glb,`${base}/model.glb`):null,fbx:m.fbx?await take(m.fbx,`${base}/model.fbx`):null};
    if(entry.glb||entry.fbx)manifest[group][e.id]=entry;else missing.push(`${e.name}: model file missing on server`);
  }
  const KIT={'Palm tree':'palm','Street tree':'tree','Street lamp':'lamp'};
  for(const k of d.kit||[]){const m=k.art?.model,name=KIT[k.kind];if(!m||!name||manifest.kit[name])continue;
    const base=`Import/kit/${name}`;const entry={glb:m.glb?await take(m.glb,`${base}/model.glb`):null,fbx:m.fbx?await take(m.fbx,`${base}/model.fbx`):null};
    if(entry.glb||entry.fbx)manifest.kit[name]=entry;}
  add('Import/manifest.json',JSON.stringify(manifest,null,2)); // paths are relative to the project root
  add('README.md',readme(title,missing,engine));
  add('BuildGame.bat',buildBat());
  add('.gitignore','Binaries/\nIntermediate/\nSaved/\nDerivedDataCache/\nBuild/\n');
  return {zip:createZip(files),name:root,missing};
}

